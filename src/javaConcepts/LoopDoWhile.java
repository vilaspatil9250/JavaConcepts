package javaConcepts;

public class LoopDoWhile {

	public static void main(String[] args) {

		int a = 1;
		do {
			System.out.println(a);
			a++;
		} while(a<=10);

		System.out.println("==========================");
		
		char b = 'a';
		
		do{
			System.out.println(b + " = " + (int)b);
			b++;
		}while(b<= 'z');
		
		System.out.println("==========================");
		
		//nested do...while
		
		
		
		
		
		
	}

}
